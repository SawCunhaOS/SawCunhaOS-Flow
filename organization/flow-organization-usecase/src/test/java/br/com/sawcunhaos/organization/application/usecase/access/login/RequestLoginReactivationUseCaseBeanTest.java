package br.com.sawcunhaos.organization.application.usecase.access.login;

import br.com.sawcunhaos.organization.domain.access.login.specification.LoginService;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

import static org.mockito.Mockito.verify;

@ExtendWith(MockitoExtension.class)
class RequestLoginReactivationUseCaseBeanTest {

    @Mock
    private LoginService loginService;

    @InjectMocks
    private RequestLoginReactivationUseCaseBean useCase;

    @Test
    void executeShouldDelegateToLoginService() {
        useCase.execute(10L);

        verify(loginService).requestReactivation(10L);
    }
}
