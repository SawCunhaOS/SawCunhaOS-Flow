package br.com.sawcunhaos.organization.domain.repository.login;

import br.com.sawcunhaos.organization.domain.model.login.Profile;
import io.hypersistence.utils.spring.repository.BaseJpaRepository;
import org.springframework.data.jpa.repository.JpaSpecificationExecutor;
import org.springframework.data.querydsl.QuerydslPredicateExecutor;
import org.springframework.stereotype.Repository;
import org.springframework.transaction.annotation.Transactional;

import java.util.Optional;

@Repository
@Transactional(readOnly = true)
public interface ProfileRepository extends BaseJpaRepository<Profile, Long>, JpaSpecificationExecutor<Profile>, QuerydslPredicateExecutor<Profile> {

    Optional<Profile> findByCode(String code);

}
